#!/usr/bin/env node
// Copies the shared canonical files from notification-sender into the apps that need them.
// Connect builds each app in isolation, so a file: dependency cannot work; vendoring is the only option.
// Usage: node tools/sync-shared.mjs          (write the copies)
//        node tools/sync-shared.mjs --check  (exit 1 if a copy is missing or out of date)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Paths relative to notification-sender/src. Keep their own imports relative so they resolve in every copy. */
const SHARED_FILES = [
  'sms/render-sms.ts',
  'notifications/keys.ts',
  'mappings/notification-mapping.ts',
  // Pure builders and sample data. They only import types from @commercetools/platform-sdk.
  { path: 'notifications/template-data.ts', targets: ['notification-manager/src/shared'] },
  { path: 'notifications/samples.ts', targets: ['notification-manager/src/shared'] },
  // The default localization texts, as a TypeScript module so the Merchant Center bundles them without a JSON loader.
  {
    path: 'utils/localizations.json',
    output: 'localizations.ts',
    targets: ['notification-manager/src/shared'],
    transform: (source) =>
      `export type DefaultLocalizations = {\n  name: Record<string, string>;\n  entries: Array<{\n    key: string;\n    name: Record<string, string>;\n    values: Array<{ key: string; label: Record<string, string> }>;\n  }>;\n};\n\nexport const DEFAULT_LOCALIZATIONS: DefaultLocalizations = ${source.trim()};\n`,
  },
];
const SOURCE_DIR = 'notification-sender/src';
const TARGET_DIRS = ['notification-manager/src/shared'];

const headerFor = (relativePath) =>
  `// GENERATED by tools/sync-shared.mjs from notification-sender/src/${relativePath} — do not edit.\n`;

const checkOnly = process.argv.includes('--check');
let problems = 0;

for (const entry of SHARED_FILES) {
  const relativePath = typeof entry === 'string' ? entry : entry.path;
  const targets = typeof entry === 'string' ? TARGET_DIRS : entry.targets;
  const raw = readFileSync(join(ROOT, SOURCE_DIR, relativePath), 'utf8');
  const source = typeof entry === 'string' || !entry.transform ? raw : entry.transform(raw);
  const outputPath = typeof entry === 'string' ? relativePath : entry.output ?? relativePath;
  const expected = headerFor(relativePath) + source;
  for (const targetDir of targets) {
    const targetPath = join(ROOT, targetDir, outputPath);
    if (checkOnly) {
      const actual = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : undefined;
      if (actual !== expected) {
        problems += 1;
        console.error(`out of date: ${targetDir}/${outputPath}`);
      }
    } else {
      mkdirSync(dirname(targetPath), { recursive: true });
      writeFileSync(targetPath, expected);
      console.log(`synced ${targetDir}/${outputPath}`);
    }
  }
}

if (checkOnly) {
  if (problems > 0) {
    console.error(`${problems} shared file copy(ies) out of date. Run: npm run sync:shared`);
    process.exit(1);
  }
  console.log('Shared files are in sync.');
}
